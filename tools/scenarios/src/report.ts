/** Renders docs/catalog/shortlist.md [req. 5]. */
import type { ScreenedEntry } from '@takes/catalog';

function fmt(n: number, d = 2): string { return n.toFixed(d); }

export function renderShortlistMd(byFamily: Map<string, ScreenedEntry[]>, timings: Array<{ id: string; stage: string; ms: number; games: number }>): string {
  const lines: string[] = ['# Scenario shortlist', '', '_Generated by tools/scenarios. See docs/catalog/PLAN.md steps 5-7._', ''];
  for (const [family, entries] of byFamily) {
    lines.push(`## ${family}`, '');
    if (entries.length === 0) { lines.push('_no candidates_', ''); continue; }
    lines.push('| piece | betza | tier | games | score | score CI | moves/g | captures/g | checks/g | forks/g | survival | finalAttack | decisive | excluded |');
    lines.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
    for (const e of entries) {
      const m = e.metrics;
      lines.push(
        `| ${e.piece.name} (${e.piece.id}) | ${e.betza} | ${e.tier} | ${m.games} | ${fmt(m.score)} | [${fmt(m.scoreCI[0])}, ${fmt(m.scoreCI[1])}] | ${fmt(m.movesPerGame)} | ${fmt(m.capturesPerGame)} | ${fmt(m.checksPerGame)} | ${fmt(m.forksPerGame)} | ${fmt(m.survival)} | ${fmt(m.finalAttack)} | ${fmt(m.decisive)} | ${m.excluded} |`,
      );
    }
    lines.push('');
  }
  lines.push('## Throughput', '', '| candidate | stage | games | wall ms | ms/game |', '|---|---|---|---|---|');
  for (const t of timings) {
    const perGame = t.games > 0 ? Math.round(t.ms / t.games) : 0;
    lines.push(`| ${t.id} | ${t.stage} | ${t.games} | ${t.ms} | ${perGame} |`);
  }
  lines.push('');
  return lines.join('\n');
}
