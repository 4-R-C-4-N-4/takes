// Snapshot pieces/*/piece.json into immutable rulesets [D4].
// Usage: node --experimental-strip-types packages/library/scripts/build-rulesets.ts [--force]
// Writes rulesets/<v>.json and src/rulesets/<v>.ts. A published ruleset (its <v>.json exists) is
// FROZEN: its pinned piece definitions are kept even if pieces/*/piece.json has since changed
// (e.g. a later version re-tiers a piece), so editing a piece only affects new versions. Editing a
// published version's config (costs, pool, caps, promotion) is an error. --force re-snapshots.
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const force = process.argv.includes('--force');
const configs = readdirSync(join(root, 'rulesets')).filter((f) => f.endsWith('.config.json'));
mkdirSync(join(root, 'src/rulesets'), { recursive: true });
const index: string[] = [];
for (const cf of configs) {
  const cfg = JSON.parse(readFileSync(join(root, 'rulesets', cf), 'utf8'));
  const pieces: Record<string, unknown> = {};
  for (const id of Object.keys(cfg.costs)) {
    pieces[id] = JSON.parse(readFileSync(join(root, 'pieces', id, 'piece.json'), 'utf8'));
  }
  const rs = { version: cfg.version, pieces, costs: cfg.costs, pool: cfg.pool, maxCount: cfg.maxCount,
    promotionMode: cfg.promotionMode, promotionTargets: cfg.promotionTargets, promotionFallback: cfg.promotionFallback, maxPlies: cfg.maxPlies };
  const text = JSON.stringify(rs, null, 2) + '\n';
  const out = join(root, 'rulesets', `${cfg.version}.json`);
  let published = text;
  if (existsSync(out) && !force) {
    published = readFileSync(out, 'utf8');
    const frozen = JSON.parse(published);
    const configOf = (x: typeof rs) => JSON.stringify([x.costs, x.pool, x.maxCount, x.promotionMode, x.promotionTargets, x.promotionFallback, x.maxPlies]);
    if (configOf(frozen) !== configOf(rs)) {
      console.error(`ruleset ${cfg.version} is published; its config changed. Publish a new version instead (or pass --force).`);
      process.exit(1);
    }
    if (published !== text) console.log(`ruleset ${cfg.version} is frozen: keeping its published piece snapshots`);
  } else {
    writeFileSync(out, text);
  }
  const ident = 'r' + cfg.version.replace(/\W/g, '_');
  writeFileSync(join(root, 'src/rulesets', `${cfg.version}.ts`),
    `// GENERATED by scripts/build-rulesets.ts — do not edit.\nimport type { RulesetJSON } from '../load.js';\nexport const ${ident}: RulesetJSON = ${published.trimEnd()};\n`);
  index.push(`export { ${ident} } from './${cfg.version}.js';`);
  console.log(`built ruleset ${cfg.version} (${Object.keys(JSON.parse(published).pieces).length} pieces)`);
}
writeFileSync(join(root, 'src/rulesets/index.ts'), '// GENERATED\n' + index.join('\n') + '\n');
